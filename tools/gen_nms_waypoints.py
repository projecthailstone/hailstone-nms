#!/usr/bin/env python3
"""Writes plugins/nms/nms_waypoints.inc: each NMS waypoint's long name, zone short name and expansion,
for the NMS plugin's waypoint window. OP_WaypointList sends only the long name and the continent category,
so the window takes the expansion from this table (the server's zone.expansion, EQEmu numbering).

Reads the rows on stdin, tab-separated: long_name, short_name, category, expansion. With the NMS server's
Docker stack (NMS-Release) running:

  docker exec nms-db mariadb -upeq -p"$DB_PASSWORD" peq -N -e "select w.long_name, w.shortname, w.category,
      coalesce(z.expansion, -1) from nms_waypoints w left join zone z on z.short_name = w.shortname
      and z.version = 0 order by w.id" | tools/gen_nms_waypoints.py > plugins/nms/nms_waypoints.inc

plugins/projecttriune/triune_waypoints.inc (a private plugin, when checked out) is the same output (a copy of the NMS server's table until Triune's own
rows are known); regenerate it the same way with that file as the destination.
"""
import sys


def c_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


rows = []
for line in sys.stdin:
    line = line.rstrip("\n")
    if not line:
        continue
    long_name, short, category, expansion = line.split("\t")
    rows.append((long_name, short, int(category), int(expansion)))

print("// Generated by tools/gen_nms_waypoints.py from the NMS server's nms_waypoints and zone tables. Do not edit")
print(f"// by hand. {len(rows)} waypoints: NMSC_WAYPOINT(long name, zone short name, category, expansion).")
for long_name, short, category, expansion in rows:
    print(f"NMSC_WAYPOINT({c_string(long_name)}, {c_string(short)}, {category}, {expansion})")
